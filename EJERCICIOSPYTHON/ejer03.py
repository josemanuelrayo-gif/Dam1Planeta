n=int(input("Dime el nº de mes"))
print(n)

if n>=1 and n<=3:
    print("Primer trimestre")
elif n>=4 and n<=6:
    print("Segundo trimestre")
elif n>=7 and n<=9:
    print("Tercer trimestre")    
elif n>=10 and n<=12:
    print("Cuarto trimestre")
else:
    print("El numero de mes tiene que estar entre 1 y 12")    

